import { lstatSync, readFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

export const MARCA_DO_PEDIDO = '<!-- pedido v1 · orquestradora -->';
export const marcaDaEntrega = (executora) => `<!-- entrega · executora ${executora} -->`;

const TETO_DO_ARQUIVO = 2 * 1024 * 1024;
const TETO_DE_LINHAS = 60;
const TETO_DA_ANALISE = 60000;
const SECOES = ['Objetivo', 'Contexto', 'Decisões', 'Critério de pronto', 'Fora'];
const CABECALHO = ['Despacho', 'Origem', 'Repositório', 'Limite'];
const CAMPOS_DA_CONFIG = new Set(['versao', 'issues', 'autores', 'etiquetas', 'executoras', 'repositorios']);
const MODOS = new Set(['codigo', 'analise']);
const REPOSITORIO = /^[A-Za-z0-9_.-]+\/[A-Za-z0-9_.-]+$/;
const LOGIN = /^[A-Za-z0-9][A-Za-z0-9-]{0,38}(?:\[bot\])?$/;
const NOME = /^[a-z0-9]+(?:-[a-z0-9]+)*$/;
const BRANCH = /^branch `(claude\/pedido-[a-z0-9]+(?:-[a-z0-9]+)*)`$/;
const DATA = /^\d{4}-\d{2}-\d{2}$/;
const HORA = '\\d{4}-\\d{2}-\\d{2} \\d{2}:\\d{2}Z';
const RETORNO = new RegExp(`^## (Devolução|Resposta) (\\d+) · ${HORA}$`);
const RETORNO_SOLTO = /^## (?:Devolução|Resposta)\b/;
const CRITERIO = /^- \[[ xX]\] \S.* · prova: \S/;
const RODAPE = /\n+---\n+_Generated by [^\n]*_\s*$/;
const ENTREGA_DE_CODIGO = new RegExp(
  `^\\*\\*Entrega:\\*\\* \`(claude\\/pedido-[a-z0-9-]+)\` · (?:\`([0-9a-f]{7,40})\`|sem commit) · rodada (\\d+) · ${HORA}$`,
);
const ENTREGA_DE_ANALISE = new RegExp(`^\\*\\*Entrega:\\*\\* análise · rodada (\\d+) · ${HORA}$`);
const LEITURA = /^`([A-Za-z0-9_.-]+\/[A-Za-z0-9_.-]+)` `([0-9a-f]{7,40})`$/;
const PONTOS = [/^1\. O que mudou: \S/, /^2\. Por quê: \S/, /^3\. O que foi testado: \S/, /^4\. Risco e reversão: \S/,
  /^5\. Como conferir: \S/, /^\*\*Critérios:\*\* \S/];
const SEGREDOS = [
  /\b(?:AKIA|ASIA)[0-9A-Z]{16}\b/,
  /\bgh[pousr]_[A-Za-z0-9]{30,}/,
  /\bgithub_pat_[A-Za-z0-9_]{30,}/,
  /-----BEGIN [A-Z ]*PRIVATE KEY-----/,
  /\bsk-[A-Za-z0-9_-]{20,}/,
  /\bxox[abprs]-[A-Za-z0-9-]{10,}/,
];
const EMAIL = /[\w.+-]+@[\w-]+(?:\.[\w-]+)*\.[a-z]{2,}\b/i;

export class ErroDePedido extends Error {
  constructor(mensagem) {
    super(mensagem);
    this.name = 'ErroDePedido';
  }
}

const falhar = (mensagem) => { throw new ErroDePedido(mensagem); };
const objeto = (valor) => typeof valor === 'object' && valor !== null && !Array.isArray(valor);
const preenchido = (valor) => typeof valor === 'string' && valor.trim() !== '';
const mesmo = (a, b) => a.toLowerCase() === b.toLowerCase();
const partes = (valor) => valor.split(' · ').map((parte) => parte.trim());

function linhasDe(corpo) {
  return corpo.replace(/\r\n?/g, '\n').replace(RODAPE, '').split('\n');
}

function tamanho(linhas) {
  return linhas.filter((linha) => linha.trim()).reduce((soma, linha) => soma + Math.ceil(linha.length / 120), 0);
}

function semSegredo(texto, onde) {
  if (SEGREDOS.some((padrao) => padrao.test(texto))) falhar(`segredo ${onde}`);
  if (EMAIL.test(texto)) falhar(`e-mail ${onde}`);
}

export function lerConfig(config) {
  if (!objeto(config)) falhar('configuração inválida');
  for (const campo of Object.keys(config)) if (!CAMPOS_DA_CONFIG.has(campo)) falhar('configuração com campo desconhecido');
  for (const campo of CAMPOS_DA_CONFIG) if (!Object.hasOwn(config, campo)) falhar('configuração com campo ausente');
  if (config.versao !== 1) falhar('configuração de versão inválida');
  if (typeof config.issues !== 'string' || !REPOSITORIO.test(config.issues)) falhar('configuração sem repositório de issues');
  const { autores, etiquetas, executoras, repositorios } = config;
  if (!Array.isArray(autores) || !autores.length || !autores.every((autor) => typeof autor === 'string' && LOGIN.test(autor))) {
    falhar('configuração sem autores');
  }
  if (!objeto(etiquetas) || Object.keys(etiquetas).some((k) => !['pedido', 'conferir', 'aceito', 'dono'].includes(k))
    || ['aceito', 'dono'].some((k) => Object.hasOwn(etiquetas, k) && !preenchido(etiquetas[k]))
    || !preenchido(etiquetas.pedido) || !preenchido(etiquetas.conferir)) {
    falhar('configuração com etiquetas inválidas');
  }
  if (!objeto(executoras) || !Object.keys(executoras).length) falhar('configuração sem executoras');
  for (const [nome, etiqueta] of Object.entries(executoras)) {
    if (!NOME.test(nome) || !preenchido(etiqueta)) falhar('configuração com executora inválida');
  }
  const todas = [...Object.values(etiquetas), ...Object.values(executoras)].map((etiqueta) => etiqueta.toLowerCase());
  if (new Set(todas).size !== todas.length) falhar('configuração com etiqueta repetida');
  if (!objeto(repositorios) || !Object.keys(repositorios).length) falhar('configuração sem repositórios');
  for (const [nome, modo] of Object.entries(repositorios)) {
    if (!REPOSITORIO.test(nome) || !MODOS.has(modo)) falhar('configuração com repositório inválido');
  }
  return config;
}

function modoDoRepositorio(config, nome) {
  const achado = Object.keys(config.repositorios).find((repositorio) => mesmo(repositorio, nome));
  if (!achado) falhar('repositório fora da lista');
  return config.repositorios[achado];
}

function lerRetornos(linhas) {
  const contagem = { Devolução: 0, Resposta: 0 };
  for (const linha of linhas) {
    if (!RETORNO_SOLTO.test(linha)) continue;
    const achado = RETORNO.exec(linha);
    if (!achado) falhar('devolução ou resposta fora do molde');
    const [, tipo, numero] = achado;
    contagem[tipo] += 1;
    if (Number(numero) !== contagem[tipo]) falhar('devolução ou resposta fora de ordem');
  }
  return contagem;
}

function lerCabecalho(linhas) {
  const fim = linhas.findIndex((linha) => linha.startsWith('## '));
  const topo = fim === -1 ? linhas : linhas.slice(0, fim);
  const campos = {};
  for (const campo of CABECALHO) {
    const prefixo = `**${campo}:** `;
    const achadas = topo.filter((linha) => linha.startsWith(prefixo));
    if (achadas.length !== 1 || !preenchido(achadas[0].slice(prefixo.length))) falhar(`cabeçalho sem ${campo}`);
    campos[campo] = achadas[0].slice(prefixo.length).trim();
  }
  return campos;
}

function lerSecoes(linhas) {
  const secoes = [];
  for (const linha of linhas) {
    if (linha.startsWith('## ')) secoes.push({ nome: linha.slice(3).trim(), linhas: [] });
    else if (secoes.length) secoes.at(-1).linhas.push(linha);
  }
  const nomes = secoes.map((secao) => secao.nome).join('|');
  const analise = nomes === [...SECOES, 'Entrega'].join('|');
  if (!analise && nomes !== SECOES.join('|')) falhar('seções fora do molde');
  for (const secao of secoes) if (!secao.linhas.some((linha) => linha.trim())) falhar('seção vazia');
  const criterios = secoes.find((secao) => secao.nome === 'Critério de pronto').linhas.filter((linha) => linha.startsWith('- ['));
  if (!criterios.length || !criterios.every((linha) => CRITERIO.test(linha))) falhar('critério sem prova');
  return { analise, criterios };
}

function lerRepositorio(config, valor, analise) {
  const [primeira, ...resto] = partes(valor);
  const nomes = [...primeira.matchAll(/`([^`]+)`/g)].map((achado) => achado[1]);
  if (!nomes.length || !nomes.every((nome) => REPOSITORIO.test(nome))) falhar('repositório fora do molde');
  const modos = nomes.map((nome) => modoDoRepositorio(config, nome));
  if (!resto.some((parte) => /^base `[^`\s]+`$/.test(parte))) falhar('repositório sem base');
  const branches = resto.map((parte) => BRANCH.exec(parte)).filter(Boolean);
  const semBranch = resto.some((parte) => parte.startsWith('sem branch'));
  if (analise) {
    if (branches.length || !semBranch) falhar('análise com branch');
    return { repositorios: nomes, branch: null };
  }
  if (nomes.length !== 1) falhar('código em mais de um repositório');
  if (modos[0] !== 'codigo') falhar('repositório só de análise');
  if (branches.length !== 1 || semBranch) falhar('código sem branch');
  return { repositorios: nomes, branch: branches[0][1] };
}

export function conferirCorpo(config, corpo) {
  lerConfig(config);
  if (!preenchido(corpo)) falhar('corpo vazio');
  const linhas = linhasDe(corpo);
  if (linhas[0] !== MARCA_DO_PEDIDO) falhar('sem a marca do pedido');
  semSegredo(corpo, 'no corpo');
  const corte = linhas.findIndex((linha) => RETORNO_SOLTO.test(linha));
  const original = corte === -1 ? linhas : linhas.slice(0, corte);
  const retornos = lerRetornos(linhas);
  const campos = lerCabecalho(original);
  const { analise, criterios: linhasCriterios } = lerSecoes(original);
  if (partes(campos.Despacho).length < 4 || !partes(campos.Despacho).every(Boolean)) falhar('despacho fora do molde');
  const origem = partes(campos.Origem);
  if (origem.length < 3 || !origem.every(Boolean) || !DATA.test(origem.at(-1))) falhar('origem fora do molde');
  const numeros = linhasCriterios.map((linha) => /^- \[.\] C(\d+)\s/.exec(linha)?.[1]);
  if (numeros.some(Boolean) && numeros.some((n, i) => Number(n) !== i + 1)) falhar('critérios fora de ordem ou misturados');
  if (origem.at(-1) >= '2026-11-13' && numeros.some((n) => !n)) falhar('critérios sem numeração');
  const prazo = /^(\d+)\s+(min|minutos|hora|horas)$/.exec(campos.Limite.split(';').at(-1).trim());
  const tempo = prazo ? Number(prazo[1]) * (prazo[2].startsWith('hora') ? 60 : 1) : null;
  if (origem.at(-1) >= '2026-11-13' && !tempo) falhar('limite sem tempo');
  if (analise ? original.join('\n').length > TETO_DA_ANALISE : tamanho(original) > TETO_DE_LINHAS) falhar('pedido longo demais');
  return {
    modo: analise ? 'analise' : 'codigo', tempo, criterios: numeros.filter(Boolean).map(Number),
    ...lerRepositorio(config, campos['Repositório'], analise),
    rodada: 1 + retornos['Devolução'] + retornos.Resposta,
    devolucoes: retornos['Devolução'],
  };
}

function conferirIssue(config, issue) {
  if (!objeto(issue)) falhar('issue inválida');
  if (Object.hasOwn(issue, 'pull_request')) falhar('é pull request');
  if (typeof issue.repository_url !== 'string' || !mesmo(issue.repository_url.split('/repos/').at(-1) ?? '', config.issues)) {
    falhar('issue de outro repositório');
  }
  const login = issue.user?.login;
  if (typeof login !== 'string' || !config.autores.some((autor) => mesmo(autor, login))) falhar('autor fora da lista');
  if (!Array.isArray(issue.labels)) falhar('issue sem etiquetas');
}

function executoraConhecida(config, executora) {
  if (typeof executora !== 'string' || !Object.hasOwn(config.executoras, executora)) falhar('executora desconhecida');
}

export function vez(config, issue) {
  lerConfig(config);
  conferirIssue(config, issue);
  if (issue.state === 'closed') return { estado: 'fechado' };
  const nomes = new Set(issue.labels.map((etiqueta) => (typeof etiqueta === 'string' ? etiqueta : etiqueta?.name))
    .filter((nome) => typeof nome === 'string').map((nome) => nome.toLowerCase()));
  if (!nomes.has(config.etiquetas.pedido.toLowerCase())) falhar('sem a etiqueta do pedido');
  const candidatas = [['conferir', config.etiquetas.conferir], ...['aceito', 'dono'].filter((k) => config.etiquetas[k]).map((k) => [k, config.etiquetas[k]]), ...Object.entries(config.executoras)]
    .filter(([, etiqueta]) => nomes.has(etiqueta.toLowerCase()));
  if (candidatas.length > 1) falhar('mais de uma etiqueta da vez');
  if (!candidatas.length) {
    if (config.etiquetas.aceito || config.etiquetas.dono) falhar('sem etiqueta da vez');
    return { estado: 'aceito' };
  }
  const [nome, etiqueta] = candidatas[0];
  if (['conferir', 'aceito', 'dono'].includes(nome) && etiqueta === config.etiquetas[nome]) return { estado: nome };
  return { estado: 'executora', executora: nome };
}

export function conferirPedido(config, issue, executora, etiquetaDoEvento) {
  lerConfig(config);
  executoraConhecida(config, executora);
  conferirIssue(config, issue);
  if (issue.state !== 'open') falhar('pedido fechado');
  if (etiquetaDoEvento !== undefined && !mesmo(etiquetaDoEvento, config.executoras[executora])) falhar('evento de outra etiqueta');
  const atual = vez(config, issue);
  if (atual.estado !== 'executora' || atual.executora !== executora) falhar('a vez não é desta executora');
  return { ...conferirCorpo(config, issue.body), executora };
}

function lerLeitura(linhas, repositorios) {
  const achadas = linhas.filter((linha) => linha.startsWith('**Lido:** '));
  if (achadas.length !== 1) falhar('análise sem a linha do que leu');
  const lidos = new Map();
  for (const parte of partes(achadas[0].slice('**Lido:** '.length))) {
    const achado = LEITURA.exec(parte);
    if (!achado) falhar('leitura fora do molde');
    lidos.set(achado[1].toLowerCase(), achado[2]);
  }
  if (!repositorios.every((nome) => lidos.has(nome.toLowerCase()))) falhar('leitura sem o SHA de um repositório');
}

export function conferirEntrega(config, issue, comentarios, executora) {
  lerConfig(config);
  executoraConhecida(config, executora);
  conferirIssue(config, issue);
  if (!Array.isArray(comentarios)) falhar('comentários inválidos');
  const marca = marcaDaEntrega(executora);
  const dela = comentarios.filter((comentario) => objeto(comentario) && typeof comentario.body === 'string'
    && linhasDe(comentario.body)[0] === marca);
  if (!dela.length) falhar('entrega ausente');
  if (dela.length > 1) falhar('entrega repetida');
  const corpo = dela[0].body;
  semSegredo(corpo, 'na entrega');
  const linhas = linhasDe(corpo);
  const recebidos = linhas.filter((linha) => linha.startsWith('**Recebido:**'));
  if (recebidos.length && (recebidos.length !== 1 || linhas[1] !== recebidos[0] || !new RegExp(`^\\*\\*Recebido:\\*\\* ${HORA}$`).test(recebidos[0]))) falhar('recebido fora do molde');
  const recusas = linhas.filter((linha) => /^\*\*Recusado:\*\* \S/.test(linha));
  if (recusas.length === 1 && !linhas.some((linha) => linha.startsWith('**Entrega:**'))) {
    if (!recebidos.length) falhar('recusado sem recebido');
    return { recusado: recusas[0].slice('**Recusado:** '.length) };
  }
  const pedido = conferirCorpo(config, issue.body);
  const cabecalho = linhas.filter((linha) => linha.startsWith('**Entrega:** '));
  if (cabecalho.length !== 1) falhar('linha de entrega ausente');
  const travado = linhas.some((linha) => /^\*\*Travado:\*\* \S/.test(linha));
  let rodada;
  let sha = null;
  if (pedido.modo === 'analise') {
    const achado = ENTREGA_DE_ANALISE.exec(cabecalho[0]);
    if (!achado) falhar('linha de entrega fora do molde');
    rodada = Number(achado[1]);
    if (!travado) lerLeitura(linhas, pedido.repositorios);
  } else {
    const achado = ENTREGA_DE_CODIGO.exec(cabecalho[0]);
    if (!achado) falhar('linha de entrega fora do molde');
    if (achado[1] !== pedido.branch) falhar('branch divergente');
    sha = achado[2] ?? null;
    rodada = Number(achado[3]);
    if (!travado) {
      if (!sha) falhar('entrega sem commit');
      for (const ponto of PONTOS) if (!linhas.some((linha) => ponto.test(linha))) falhar('entrega sem um dos 5 pontos ou os critérios');
    }
  }
  if (!travado && pedido.criterios.length) {
    const linha = linhas.find((l) => l.startsWith('**Critérios:** ')) ?? '';
    for (const numero of pedido.criterios) if (!new RegExp(`(?:^|\\s|·)C${numero}\\s+(?:ok|falta:)`).test(linha)) falhar(`critério C${numero} ausente na entrega`);
  }
  if (rodada !== pedido.rodada) falhar('rodada divergente');
  return { executora, modo: pedido.modo, rodada, travado, sha };
}

function lerArquivo(caminho) {
  if (!preenchido(caminho)) falhar('caminho vazio');
  let estado;
  try {
    estado = lstatSync(caminho);
  } catch (erro) {
    falhar(erro?.code === 'ENOENT' ? 'arquivo ausente' : 'arquivo indisponível');
  }
  if (estado.isSymbolicLink() || !estado.isFile()) falhar('caminho simbólico ou não é arquivo');
  if (estado.size > TETO_DO_ARQUIVO) falhar('arquivo grande demais');
  try {
    return readFileSync(caminho, 'utf8');
  } catch {
    falhar('arquivo indisponível');
  }
}

function lerJson(caminho) {
  const texto = lerArquivo(caminho);
  try {
    return JSON.parse(texto);
  } catch {
    falhar('JSON inválido');
  }
}

function descrever(resultado) {
  const modo = resultado.modo === 'analise' ? 'análise' : 'código';
  return [modo, `rodada ${resultado.rodada}`, resultado.branch].filter(Boolean).join(' · ');
}

export function executar(argumentos = process.argv.slice(2)) {
  const [modo, ...resto] = argumentos;
  if (modo === 'corpo' && resto.length === 2) {
    const resultado = conferirCorpo(lerConfig(lerJson(resto[0])), lerArquivo(resto[1]));
    return `corpo válido · ${descrever(resultado)}`;
  }
  if (modo === 'pedido' && (resto.length === 3 || resto.length === 4)) {
    const [config, issue, executora, etiqueta] = resto;
    const resultado = conferirPedido(lerConfig(lerJson(config)), lerJson(issue), executora, etiqueta);
    return `pedido válido · ${descrever(resultado)}`;
  }
  if (modo === 'entrega' && resto.length === 4) {
    const [config, issue, comentarios, executora] = resto;
    const resultado = conferirEntrega(lerConfig(lerJson(config)), lerJson(issue), lerJson(comentarios), executora);
    if (resultado.recusado) return `recusado · ${resultado.recusado}`;
    return `entrega válida · rodada ${resultado.rodada}${resultado.travado ? ' · travado' : ''}`;
  }
  falhar('uso inválido');
}

function principal() {
  try {
    process.stdout.write(`${executar()}\n`);
  } catch (erro) {
    const motivo = erro instanceof ErroDePedido ? erro.message : 'falha desconhecida';
    const quem = process.argv[2] === 'entrega' ? 'entrega inválida' : 'pedido inválido';
    process.stderr.write(`${quem}: ${motivo}\n`);
    process.exitCode = 1;
  }
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) principal();
